import path from 'node:path'
import { err } from '../../errors.js'
import type { CutSegment, SubtitleStyle } from './types.js'
import { DEFAULT_SUBTITLE_STYLE } from './types.js'

/**
 * 字幕引擎（任务书 FR-S / CE1，平移 AI-Studio VideoSubtitle.ts 的 ASS 链路）：
 *  - 句级字幕：base 时间轴每句一条 Dialogue；超长句 extractLines 换行（中文 20 字/行、≤2 行）；
 *  - PlayRes 竖屏 1080×1920（AI-Studio 原版 1920×1080 横屏，R7 修正）；
 *  - 字体走 fontsdir + fontfile（不依赖系统 fontconfig）。
 */

const HEX_COLOR = /^#[0-9a-fA-F]{6}$/

export function validateStyle(input: Partial<SubtitleStyle> | undefined): SubtitleStyle {
  const s = { ...DEFAULT_SUBTITLE_STYLE, ...(input ?? {}) }
  if (!s.fontName || s.fontName.includes('/') || s.fontName.includes('\\') || s.fontName.includes('..')) {
    throw err.cutStyleInvalid('字体不在白名单内')
  }
  if (!Number.isFinite(s.fontSize) || s.fontSize < 24 || s.fontSize > 96) throw err.cutStyleInvalid('字号须在 24~96 之间')
  for (const key of ['fontColor', 'outlineColor', 'backgroundColor'] as const) {
    if (!HEX_COLOR.test(s[key])) throw err.cutStyleInvalid(`${key} 须为 #RRGGBB`)
  }
  if (!Number.isFinite(s.outlineWidth) || s.outlineWidth < 0 || s.outlineWidth > 8) throw err.cutStyleInvalid('描边宽度须在 0~8 之间')
  if (!Number.isFinite(s.backgroundOpacity) || s.backgroundOpacity < 0 || s.backgroundOpacity > 1) {
    throw err.cutStyleInvalid('背景不透明度须在 0~1 之间')
  }
  if (!['top', 'center', 'bottom'].includes(s.position)) throw err.cutStyleInvalid('position 不合法')
  if (!['center', 'left', 'right'].includes(s.alignment)) throw err.cutStyleInvalid('alignment 不合法')
  return s
}

/** 换行（R2 平移 extractLines）：中文每行 ≤20 字、最多 2 行 */
export function extractLines(text: string, maxCharsPerLine = 20, maxLines = 2): string[] {
  const lines: string[] = []
  let rest = text
  while (rest.length > 0 && lines.length < maxLines) {
    lines.push(rest.slice(0, maxCharsPerLine))
    rest = rest.slice(maxCharsPerLine)
  }
  if (rest.length > 0) lines[maxLines - 1] = lines[maxLines - 1]! + rest
  return lines
}

/** #RRGGBB → ASS &HAABBGGRR（R1 平移 convertColorToASS） */
export function convertColorToASS(hex: string, opacity = 1): string {
  const r = hex.slice(1, 3)
  const g = hex.slice(3, 5)
  const b = hex.slice(5, 7)
  const alpha = Math.round((1 - opacity) * 255)
  const h = (n: string) => n.toUpperCase().padStart(2, '0')
  return `&H${h(alpha.toString(16))}${h(b)}${h(g)}${h(r)}&`
}

/** 秒 → ASS 时间 H:MM:SS.cc（R1 平移 formatASSTime） */
export function formatASSTime(totalSeconds: number): string {
  const s = Math.max(0, totalSeconds)
  const h = Math.floor(s / 3600)
  const m = Math.floor((s % 3600) / 60)
  const sec = Math.floor(s % 60)
  const cs = Math.floor((s - Math.floor(s)) * 100)
  return `${h}:${String(m).padStart(2, '0')}:${String(sec).padStart(2, '0')}.${String(cs).padStart(2, '0')}`
}

/** ASS numpad Alignment：position × alignment（R1） */
function assAlignment(style: SubtitleStyle): number {
  const col = style.alignment === 'left' ? 0 : style.alignment === 'right' ? 2 : 1
  switch (style.position) {
    case 'top':
      return [7, 8, 9][col]!
    case 'center':
      return [4, 5, 6][col]!
    default:
      return [1, 2, 3][col]!
  }
}

const assEscape = (t: string) => t.replace(/\\/g, '\\\\').replace(/\{/g, '（').replace(/}/g, '）').replace(/\n/g, '\\N')

export function buildAss(
  segments: CutSegment[],
  style: SubtitleStyle,
  opts: { width: number; height: number; fontFile: string },
): string {
  const alignment = assAlignment(style)
  const marginV = style.position === 'center' ? 0 : Math.round(opts.height * 0.08)
  const borderStyle = style.backgroundEnabled ? 3 : 1
  const primary = convertColorToASS(style.fontColor, 1)
  const outline = convertColorToASS(style.outlineColor, 1)
  const back = convertColorToASS(style.backgroundColor, style.backgroundOpacity)
  const fontName = path.parse(opts.fontFile).name
  const header = [
    '[Script Info]',
    '; Generated by caijing-koubo cut module (FR-S3)',
    `PlayResX: ${opts.width}`,
    `PlayResY: ${opts.height}`,
    'ScaledBorderAndShadow: yes',
    'WrapStyle: 2',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: Default,${fontName},${style.fontSize},${primary},&H00FFFFFF,${outline},${back},0,0,0,0,100,100,0,0,${borderStyle},${style.outlineWidth},1,${alignment},40,40,${marginV},1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text',
  ]
  const events = segments
    .filter((seg) => seg.text.trim())
    .map((seg) => {
      const lines = extractLines(seg.text.trim())
      const text = assEscape(lines.join('\n'))
      return `Dialogue: 0,${formatASSTime(seg.startMs / 1000)},${formatASSTime(seg.endMs / 1000)},Default,,0,0,0,,${text}`
    })
  return [...header, ...events, ''].join('\n')
}

/** 烧录参数（FR-S3）：ass 滤镜 + fontsdir（字体解析兜底） */
export function buildSubtitleFilter(assPath: string, fontFile: string, useAssFilter: boolean): string {
  const fontsDir = path.dirname(fontFile)
  const esc = (p: string) => p.replace(/\\/g, '/').replace(/:/g, '\\:').replace(/'/g, "\\'")
  const filter = useAssFilter ? 'ass' : 'subtitles'
  return `${filter}='${esc(assPath)}':fontsdir='${esc(fontsDir)}'`
}
